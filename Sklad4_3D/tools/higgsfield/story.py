lst=[]
for t,name,dur,a,b in SC:
  p=f"{src}/t{t.replace('.','_')}.jpg"
  im=Image.open(p).convert('RGB'); W,H=im.size
  # чистая копия для Higgsfield (без подписей)
  im.save(f"{out}/{name}.jpg",quality=92)
  d=ImageDraw.Draw(im,'RGBA')
  wa=d.textlength(a,font=FB); wb=d.textlength(b,font=FS); w=int(max(wa,wb))+60
  d.rectangle([40,H-170,40+w,H-40],fill=(10,14,20,170))
  d.text((70,H-158),a,font=FB,fill=(255,255,255)); d.text((70,H-92),b,font=FS,fill=(220,228,235))
  tag="HIGGSFIELD · раскадровка · сцена "+name.split('_')[0]+" · кадр фильма t="+t+" с"
  d.rectangle([40,30,40+int(d.textlength(tag,font=FT))+30,78],fill=(10,14,20,150)); d.text((55,38),tag,font=FT,fill=(255,214,80))
  im.save(f"{out}/cap_{name}.jpg",quality=90); lst.append((f"{out}/cap_{name}.jpg",dur))
json.dump(lst,open(f"{out}/list.json","w"),ensure_ascii=False)
print(len(lst),"scenes, total",sum(d for _,d in lst),"s")
